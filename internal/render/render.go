// Package render. render - the shared context, escaping rules and Markdown table
// helpers every page renderer uses. Renderers are pure functions from data to
// string: no clock, no filesystem, no map iteration order, so the same input always
// produces the same bytes.
package render

import (
	"fmt"
	"sort"
	"strings"

	"github.com/seyallius/benchbook/internal/compare"
	"github.com/seyallius/benchbook/internal/model"
	"github.com/seyallius/benchbook/internal/stats"
)

// ---------------------------------------------- Types ----------------------------------------- //

// GeneratedHeader is the first line of every generated page. It is the contract
// with the reader: this file is derived, edit the source or the config instead.
const GeneratedHeader = "<!-- generated by benchbook: DO NOT EDIT -->"

// Category is one configured group of workloads. The render package keeps its own
// copy of the shape so it never imports the config package.
type Category struct {
	// Title is the section heading.
	Title string
	// Match is a list of case-sensitive substrings tested against workload names.
	Match []string
}

// Context is everything the renderers need beyond the run data itself. The CLI
// builds it from benchbook.toml, which keeps render free of configuration parsing.
type Context struct {
	// ProjectName is the project name, used in page headers.
	ProjectName string
	// BaselineVariant is the variant other variants are compared against.
	BaselineVariant string
	// Categories are ordered; the first match wins.
	Categories []Category
	// DefaultCategory catches workloads that match no category.
	DefaultCategory Category
	// Tracked lists the headline benchmarks of the timeline.
	Tracked []string
	// MaxTracked caps how many benchmarks a timeline chart shows.
	MaxTracked int
	// ProfileTop caps the rows of a profile table.
	ProfileTop int
	// NoiseFloorNote appends the explanation of the noise floor to pages.
	NoiseFloorNote bool
	// Options are the statistical thresholds used for classification.
	Options compare.Options
}

// defaultMaxTracked caps the timeline when the configuration is silent.
const defaultMaxTracked = 12

// defaultProfileTop caps profile tables when the configuration is silent.
const defaultProfileTop = 20

// tableIndentNone marks a table that is not nested inside a list item.
const tableIndentNone = ""

// ----------------------------------------- Public API ----------------------------------------- //

// CategoryFor returns the category a workload belongs to, first match wins.
func (c Context) CategoryFor(workload string) Category {
	for _, category := range c.Categories {
		for _, needle := range category.Match {
			if strings.Contains(workload, needle) {
				return category
			}
		}
	}
	return c.DefaultCategory
}

// MaxTrackedOrDefault returns the tracked-benchmark cap.
func (c Context) MaxTrackedOrDefault() int {
	if c.MaxTracked > 0 {
		return c.MaxTracked
	}
	return defaultMaxTracked
}

// ProfileTopOrDefault returns the profile row cap.
func (c Context) ProfileTopOrDefault() int {
	if c.ProfileTop > 0 {
		return c.ProfileTop
	}
	return defaultProfileTop
}

// EscapeCell makes an arbitrary string safe inside a Markdown table cell: a pipe
// would end the cell and angle brackets would start HTML, so both are escaped, and
// newlines become <br> so a multi-line note cannot break the row.
//
// Backticks are deliberately left alone. They carry no table structure, and escaping
// them here would corrupt every code span: code() builds "`value`" and the table then
// escapes the whole cell, so escaping the fence would turn the value into a literal
// backslash-backtick in the rendered page.
func EscapeCell(value string) string {
	escaped := strings.NewReplacer(
		"&", "&amp;",
		"|", "\\|",
		"<", "&lt;",
		">", "&gt;",
		"\r\n", "<br>",
		"\n", "<br>",
		"\r", "<br>",
	).Replace(value)
	return strings.TrimSpace(escaped)
}

// EscapeText makes an arbitrary string safe in prose (headings, paragraphs): the
// characters that would start HTML or a code span are neutralised.
func EscapeText(value string) string {
	return strings.NewReplacer(
		"&", "&amp;",
		"<", "&lt;",
		">", "&gt;",
		"`", "\\`",
	).Replace(value)
}

// Badge renders the classification badge used in every table cell, so the terminal
// report and the site cannot drift apart.
func Badge(result compare.MetricResult) string {
	switch result.Classification {
	case compare.Improved:
		if !result.DeltaDefined {
			return "⚡ improved"
		}
		return fmt.Sprintf("⚡ %.1f%% faster", abs(result.DeltaPct))
	case compare.Regressed:
		if !result.DeltaDefined {
			return "🐢 regressed"
		}
		return fmt.Sprintf("🐢 %.1f%% slower", abs(result.DeltaPct))
	case compare.Unchanged:
		return "~"
	case compare.Insufficient:
		return "⚠ few samples"
	case compare.New:
		return "new"
	case compare.Removed:
		return "removed"
	case compare.Incomparable:
		return "⚠ incomparable"
	default:
		return DashPlaceholder
	}
}

// abs returns the magnitude of a value.
func abs(value float64) float64 {
	if value < 0 {
		return -value
	}
	return value
}

// SummaryCell renders a median with its spread, e.g. "15.3 µs ±3.1%".
func SummaryCell(summary stats.Summary, metric model.MetricID) string {
	if summary.N == 0 {
		return DashPlaceholder
	}
	return fmt.Sprintf("%s %s", FormatMetric(metric, summary.Median), FormatSpread(summary.Spread))
}

// Table renders a Markdown table from a header row and data rows, escaping every
// cell. Pass tableIndentNone for a top-level table.
func Table(indent string, header []string, rows [][]string) string {
	var builder strings.Builder
	builder.WriteString(indent + "| " + strings.Join(header, " | ") + " |\n")
	separators := make([]string, len(header))
	for i := range separators {
		separators[i] = "---"
	}
	builder.WriteString(indent + "| " + strings.Join(separators, " | ") + " |\n")
	for _, row := range rows {
		cells := make([]string, len(row))
		for i, cell := range row {
			cells[i] = EscapeCell(cell)
		}
		builder.WriteString(indent + "| " + strings.Join(cells, " | ") + " |\n")
	}
	return builder.String()
}

// HardwareBlock renders the "measured on" block every page ends with. Recording it
// on the page itself is what makes a printed report self-explanatory later.
func HardwareBlock(run *model.Run) string {
	if run == nil {
		return ""
	}
	provenance := run.Provenance
	var builder strings.Builder
	builder.WriteString("## Hardware & toolchain\n\n")
	builder.WriteString(Table(tableIndentNone,
		[]string{"Field", "Value"},
		[][]string{
			{"Go version", valueOrUnknown(provenance.GoVersion)},
			{"GOOS / GOARCH", fmt.Sprintf("%s / %s", valueOrUnknown(provenance.GOOS), valueOrUnknown(provenance.GOARCH))},
			{"CPU", valueOrUnknown(provenance.CPUModel)},
			{"CPU cores", countOrUnknown(provenance.CPUCores)},
			{"Memory", memoryOrUnknown(provenance.MemoryBytes)},
			{"Hardware fingerprint", code(valueOrUnknown(provenance.HardwareFingerprint))},
			{"Benchmark flags", code(valueOrUnknown(provenance.BenchArgs))},
			{"Git commit", code(shortOrUnknown(provenance.GitSHA, shortSHALength))},
			{"Git branch", valueOrUnknown(provenance.GitBranch)},
			{"Working tree", dirtyText(provenance.GitDirty)},
		}))
	return builder.String()
}

// shortSHALength is how many characters of a commit hash reports show.
const shortSHALength = 8

// valueOrUnknown renders a possibly-empty provenance value.
func valueOrUnknown(value string) string {
	if strings.TrimSpace(value) == "" {
		return "unknown"
	}
	return value
}

// countOrUnknown renders a core count, treating 0 as unknown.
func countOrUnknown(count int) string {
	if count <= 0 {
		return "unknown"
	}
	return fmt.Sprintf("%d", count)
}

// memoryOrUnknown renders a memory size in binary units.
func memoryOrUnknown(bytes uint64) string {
	if bytes == 0 {
		return "unknown"
	}
	return HumanizeBytes(float64(bytes))
}

// shortOrUnknown abbreviates a hash, treating an empty hash as unknown.
func shortOrUnknown(hash string, length int) string {
	if strings.TrimSpace(hash) == "" {
		return "unknown"
	}
	return ShortHash(hash, length)
}

// dirtyText renders the working-tree state.
func dirtyText(dirty bool) string {
	if dirty {
		return "dirty ⚠"
	}
	return "clean"
}

// code wraps a value in an inline code span, escaping it first.
// code renders a value as an inline code span. The value's own backticks are escaped
// so the span cannot be broken from the inside, and the fence itself is left for the
// table's escaping pass to preserve (see EscapeCell).
func code(value string) string {
	return "`" + strings.ReplaceAll(EscapeCell(value), "`", "\\`") + "`"
}

// SortedKeys returns the keys of a string-keyed map in ascending order, so no
// renderer ever iterates a map directly.
func SortedKeys[Value any](values map[string]Value) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
