/* benchbook documentation shell - client-side comparer.
 *
 * This is the only place where benchbook logic is duplicated in another language,
 * and it exists for one reason: the compare page has to work from static files, with
 * no server and no build step. It implements exactly the same procedure as
 * internal/stats:
 *
 *   - median, half-range/median spread;
 *   - a two-sided Mann-Whitney U test: exact rank counting when both sides have at
 *     most 50 samples and there are no ties, otherwise the normal approximation with
 *     tie correction and continuity correction;
 *   - fewer than 4 samples per side can never reach significance -> "insufficient";
 *   - a change is only labelled when p < alpha AND |Δmedian%| >= min_effect_pct;
 *   - lower is better for time/bytes/allocation metrics, higher is better for
 *     throughput units (the same explicit table as model.HigherIsBetterUnits);
 *   - a zero baseline makes the ratio undefined, so the absolute change is shown and
 *     that benchmark is excluded from the geomean.
 *
 * scripts/test-compare.mjs replays testdata/utest_vectors.json (the same golden
 * vectors the Go tests use, generated by SciPy) through this file.
 */
(function (root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory();
  } else {
    root.BenchbookCompare = factory();
  }
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  "use strict";

  var EXACT_TEST_MAX_SAMPLES = 50;
  var MIN_SAMPLES_FOR_SIGNIFICANCE = 4;

  var DEFAULT_ALPHA = 0.05;
  var DEFAULT_MIN_EFFECT_PCT = 1.0;
  var DEFAULT_MIN_SAMPLES = 6;

  var CLASS_IMPROVED = "improved";
  var CLASS_REGRESSED = "regressed";
  var CLASS_UNCHANGED = "unchanged";
  var CLASS_INSUFFICIENT = "insufficient";
  var CLASS_NEW = "new";
  var CLASS_REMOVED = "removed";
  var CLASS_INCOMPARABLE = "incomparable";

  var METRIC_NS_OP = "ns_op";
  var METRIC_BYTES_OP = "bytes_op";
  var METRIC_ALLOCS_OP = "allocs_op";
  var METRIC_ORDER = [METRIC_NS_OP, METRIC_BYTES_OP, METRIC_ALLOCS_OP];

  /* Units for which a larger value is the better outcome. Everything else is
     "lower is better". Mirrors model.higherIsBetterUnits. */
  var HIGHER_IS_BETTER_UNITS = {
    "B/s": true,
    "kB/s": true,
    "MB/s": true,
    "GB/s": true,
    "op/s": true,
    "ops/s": true,
    "req/s": true,
    "reqs/s": true,
    "item/s": true,
    "items/s": true,
    "MiB/s": true,
    "GiB/s": true
  };

  var NUMERIC_EPSILON = 1e-12;
  var LENTZ_TINY = 1e-30;
  var LENTZ_MAX_ITERATIONS = 500;

  function sortedCopy(values) {
    return values.slice().sort(function (left, right) {
      return left - right;
    });
  }

  function median(values) {
    if (!values || values.length === 0) {
      return 0;
    }
    var sorted = sortedCopy(values);
    var middle = Math.floor(sorted.length / 2);
    if (sorted.length % 2 === 1) {
      return sorted[middle];
    }
    return (sorted[middle - 1] + sorted[middle]) / 2;
  }

  function summarize(values) {
    if (!values || values.length === 0) {
      return { n: 0, median: 0, min: 0, max: 0, spread: 0 };
    }
    var sorted = sortedCopy(values);
    var middle = median(sorted);
    var min = sorted[0];
    var max = sorted[sorted.length - 1];
    var spread = middle === 0 ? 0 : (max - min) / 2 / middle;
    return { n: sorted.length, median: middle, min: min, max: max, spread: spread };
  }

  function geomean(values) {
    var logSum = 0;
    var used = 0;
    for (var index = 0; index < values.length; index++) {
      var value = values[index];
      if (!isFinite(value) || value <= 0) {
        continue;
      }
      logSum += Math.log(value);
      used++;
    }
    if (used === 0) {
      return { value: 0, count: 0 };
    }
    return { value: Math.exp(logSum / used), count: used };
  }

  function combinations(n, k) {
    if (k < 0 || k > n) {
      return 0;
    }
    if (k > n - k) {
      k = n - k;
    }
    var result = 1;
    for (var i = 1; i <= k; i++) {
      result = (result * (n - k + i)) / i;
    }
    return result;
  }

  /* rankWithTies ranks the pooled sample (ties share the average rank) and returns
     the ranks of the first group plus the tie-correction term sum(t^3 - t). */
  function rankWithTies(a, b) {
    var pooled = [];
    var index;
    for (index = 0; index < a.length; index++) {
      pooled.push({ value: a[index], group: 0, origin: index });
    }
    for (index = 0; index < b.length; index++) {
      pooled.push({ value: b[index], group: 1, origin: index });
    }
    pooled.sort(function (left, right) {
      if (left.value !== right.value) {
        return left.value - right.value;
      }
      if (left.group !== right.group) {
        return left.group - right.group;
      }
      return left.origin - right.origin;
    });

    var ranksA = new Array(a.length).fill(0);
    var tieTerm = 0;
    var start = 0;
    while (start < pooled.length) {
      var end = start + 1;
      while (end < pooled.length && pooled[end].value === pooled[start].value) {
        end++;
      }
      var averageRank = (start + 1 + end) / 2;
      if (end - start > 1) {
        var size = end - start;
        tieTerm += size * size * size - size;
      }
      for (var position = start; position < end; position++) {
        if (pooled[position].group === 0) {
          ranksA[pooled[position].origin] = averageRank;
        }
      }
      start = end;
    }
    return { ranksA: ranksA, tieTerm: tieTerm };
  }

  function uDistribution(nA, nB) {
    var dp = [];
    for (var i = 0; i <= nA; i++) {
      dp.push([]);
      for (var j = 0; j <= nB; j++) {
        var row = new Array(nA * nB + 1).fill(0);
        if (i === 0 || j === 0) {
          row[0] = 1;
        }
        dp[i].push(row);
      }
    }
    for (var x = 1; x <= nA; x++) {
      for (var y = 1; y <= nB; y++) {
        for (var u = 0; u <= x * y; u++) {
          /* P(x,y,u) = P(x,y-1,u) + P(x-1,y,u-y), mirroring internal/stats. */
          var count = dp[x][y - 1][u];
          if (u >= y) {
            count += dp[x - 1][y][u - y];
          }
          dp[x][y][u] = count;
        }
      }
    }
    return dp[nA][nB];
  }

  function exactTwoSidedP(nA, nB, u) {
    var counts = uDistribution(nA, nB);
    var total = 0;
    var limit = Math.round(u);
    for (var observed = 0; observed < counts.length; observed++) {
      if (observed <= limit) {
        total += counts[observed];
      }
    }
    return (2 * total) / combinations(nA + nB, nA);
  }

  function normalTwoSidedP(nA, nB, u, tieTerm) {
    var n = nA + nB;
    var mean = (nA * nB) / 2;
    var variance = ((nA * nB) / 12) * (n + 1 - tieTerm / (n * (n - 1)));
    if (variance <= 0) {
      return 1;
    }
    var z = (Math.abs(u - mean) - 0.5) / Math.sqrt(variance);
    if (z < 0) {
      z = 0;
    }
    return 2 * standardNormalSurvival(z);
  }

  /* erf by series expansion, valid and accurate for |x| <= 1.5. */
  function erfSeries(x) {
    var term = x;
    var sum = x;
    var xSquared = x * x;
    for (var n = 1; n < 200; n++) {
      term = (-term * xSquared * (2 * n - 1)) / (n * (2 * n + 1));
      sum += term;
      if (Math.abs(term) < Math.abs(sum) * NUMERIC_EPSILON) {
        break;
      }
    }
    return (2 / Math.sqrt(Math.PI)) * sum;
  }

  /* erfc by the Laplace continued fraction, accurate and fast for x >= 1.5. */
  function erfcContinuedFraction(x) {
    var f = x;
    var c = x;
    var d = 0;
    for (var n = 1; n <= LENTZ_MAX_ITERATIONS; n++) {
      var a = n / 2;
      d = x + a * d;
      if (d === 0) {
        d = LENTZ_TINY;
      }
      c = x + a / c;
      if (c === 0) {
        c = LENTZ_TINY;
      }
      d = 1 / d;
      var delta = c * d;
      f *= delta;
      if (Math.abs(delta - 1) < NUMERIC_EPSILON) {
        break;
      }
    }
    return Math.exp(-x * x) / Math.sqrt(Math.PI) / f;
  }

  function erfc(x) {
    if (x < 0) {
      return 2 - erfc(-x);
    }
    if (x < 1.5) {
      return 1 - erfSeries(x);
    }
    return erfcContinuedFraction(x);
  }

  /* standardNormalSurvival returns P(Z > z) for the standard normal distribution. */
  function standardNormalSurvival(z) {
    if (z < 0) {
      return 1 - standardNormalSurvival(-z);
    }
    return 0.5 * erfc(z / Math.SQRT2);
  }

  function clampProbability(p) {
    if (p < 0) {
      return 0;
    }
    if (p > 1) {
      return 1;
    }
    return p;
  }

  /* mannWhitneyU runs the same two-sided test as stats.MannWhitneyU. */
  function mannWhitneyU(a, b) {
    if (a.length < MIN_SAMPLES_FOR_SIGNIFICANCE || b.length < MIN_SAMPLES_FOR_SIGNIFICANCE) {
      return {
        error:
          "insufficient samples for a significance test (" +
          a.length +
          " vs " +
          b.length +
          ", need at least " +
          MIN_SAMPLES_FOR_SIGNIFICANCE +
          " per side)"
      };
    }
    var ranked = rankWithTies(a, b);
    var sumA = 0;
    for (var index = 0; index < ranked.ranksA.length; index++) {
      sumA += ranked.ranksA[index];
    }
    var uA = sumA - (a.length * (a.length + 1)) / 2;
    var uB = a.length * b.length - uA;
    var u = Math.min(uA, uB);
    var method = "normal";
    var p;
    if (a.length <= EXACT_TEST_MAX_SAMPLES && b.length <= EXACT_TEST_MAX_SAMPLES && ranked.tieTerm === 0) {
      method = "exact";
      p = exactTwoSidedP(a.length, b.length, u);
    } else {
      p = normalTwoSidedP(a.length, b.length, u, ranked.tieTerm);
    }
    return { u: u, p: clampProbability(p), method: method };
  }

  function isHigherBetter(metric) {
    return HIGHER_IS_BETTER_UNITS[metric] === true;
  }

  function sampleValue(sample, metric) {
    if (metric === METRIC_NS_OP) {
      return typeof sample.ns_op === "number" ? sample.ns_op : null;
    }
    if (metric === METRIC_BYTES_OP) {
      return typeof sample.bytes_op === "number" ? sample.bytes_op : null;
    }
    if (metric === METRIC_ALLOCS_OP) {
      return typeof sample.allocs_op === "number" ? sample.allocs_op : null;
    }
    if (sample.extra && typeof sample.extra[metric] === "number") {
      return sample.extra[metric];
    }
    return null;
  }

  function sampleValues(samples, metric) {
    var values = [];
    for (var index = 0; index < samples.length; index++) {
      var value = sampleValue(samples[index], metric);
      if (value !== null) {
        values.push(value);
      }
    }
    return values;
  }

  function metricsOf(samples) {
    var seen = {};
    for (var index = 0; index < samples.length; index++) {
      var sample = samples[index];
      if (typeof sample.ns_op === "number") {
        seen[METRIC_NS_OP] = true;
      }
      if (typeof sample.bytes_op === "number") {
        seen[METRIC_BYTES_OP] = true;
      }
      if (typeof sample.allocs_op === "number") {
        seen[METRIC_ALLOCS_OP] = true;
      }
      if (sample.extra) {
        Object.keys(sample.extra).forEach(function (unit) {
          seen[unit] = true;
        });
      }
    }
    return orderedMetrics(seen);
  }

  function orderedMetrics(set) {
    var out = [];
    METRIC_ORDER.forEach(function (metric) {
      if (set[metric]) {
        out.push(metric);
        delete set[metric];
      }
    });
    Object.keys(set)
      .sort()
      .forEach(function (metric) {
        out.push(metric);
      });
    return out;
  }

  function metricsOfBoth(fromSamples, toSamples) {
    var set = {};
    metricsOf(fromSamples).forEach(function (metric) {
      set[metric] = true;
    });
    metricsOf(toSamples).forEach(function (metric) {
      set[metric] = true;
    });
    return orderedMetrics(set);
  }

  function direction(metric, deltaPct) {
    if (deltaPct === 0) {
      return CLASS_UNCHANGED;
    }
    var better = deltaPct < 0;
    if (isHigherBetter(metric)) {
      better = deltaPct > 0;
    }
    return better ? CLASS_IMPROVED : CLASS_REGRESSED;
  }

  /* evaluate classifies one metric, using exactly the Go recipe: test, then minimum
     effect, then the metric's direction. */
  function evaluate(fromSamples, toSamples, metric, options) {
    var fromValues = sampleValues(fromSamples, metric);
    var toValues = sampleValues(toSamples, metric);
    var result = {
      metric: metric,
      classification: CLASS_INSUFFICIENT,
      fromMedian: 0,
      toMedian: 0,
      deltaPct: 0,
      deltaDefined: false,
      p: 0,
      tested: false,
      method: "",
      fromSamples: fromValues.length,
      toSamples: toValues.length
    };
    if (fromValues.length === 0) {
      result.classification = CLASS_NEW;
      result.toMedian = median(toValues);
      return result;
    }
    if (toValues.length === 0) {
      result.classification = CLASS_REMOVED;
      result.fromMedian = median(fromValues);
      return result;
    }
    result.fromMedian = median(fromValues);
    result.toMedian = median(toValues);
    if (result.fromMedian !== 0) {
      result.deltaPct = ((result.toMedian - result.fromMedian) / result.fromMedian) * 100;
      result.deltaDefined = true;
    }
    if (fromValues.length < MIN_SAMPLES_FOR_SIGNIFICANCE || toValues.length < MIN_SAMPLES_FOR_SIGNIFICANCE) {
      return result;
    }
    var test = mannWhitneyU(fromValues, toValues);
    if (test.error) {
      return result;
    }
    result.tested = true;
    result.p = test.p;
    result.method = test.method;
    if (test.p >= options.alpha) {
      result.classification = CLASS_UNCHANGED;
      return result;
    }
    if (!result.deltaDefined) {
      result.classification = direction(metric, 1);
      return result;
    }
    if (Math.abs(result.deltaPct) < options.minEffectPct) {
      result.classification = CLASS_UNCHANGED;
      return result;
    }
    result.classification = direction(metric, result.deltaPct);
    return result;
  }

  function headline(metrics) {
    var metric;
    for (var index = 0; index < metrics.length; index++) {
      metric = metrics[index];
      if (metric.metric === METRIC_NS_OP && metric.classification) {
        return metric.classification;
      }
    }
    for (var position = 0; position < metrics.length; position++) {
      if (metrics[position].classification) {
        return metrics[position].classification;
      }
    }
    return CLASS_INSUFFICIENT;
  }

  function indexBenchmarks(run) {
    var index = {};
    var benchmarks = (run && run.benchmarks) || [];
    for (var i = 0; i < benchmarks.length; i++) {
      index[benchmarks[i].id] = benchmarks[i];
    }
    return index;
  }

  function unionIds(fromIndex, toIndex) {
    var seen = {};
    Object.keys(fromIndex).forEach(function (id) {
      seen[id] = true;
    });
    Object.keys(toIndex).forEach(function (id) {
      seen[id] = true;
    });
    return Object.keys(seen).sort();
  }

  function displayName(name) {
    return String(name).replace(/^Benchmark/, "");
  }

  /* compareRuns mirrors compare.Between. */
  function compareRuns(from, to, rawOptions) {
    var options = {
      alpha: rawOptions && rawOptions.alpha > 0 ? rawOptions.alpha : DEFAULT_ALPHA,
      minEffectPct:
        rawOptions && typeof rawOptions.minEffectPct === "number" && rawOptions.minEffectPct >= 0
          ? rawOptions.minEffectPct
          : DEFAULT_MIN_EFFECT_PCT,
      minSamples: rawOptions && rawOptions.minSamples > 0 ? rawOptions.minSamples : DEFAULT_MIN_SAMPLES,
      forceIncomparable: !!(rawOptions && rawOptions.forceIncomparable)
    };
    var fromProvenance = (from && from.provenance) || {};
    var toProvenance = (to && to.provenance) || {};
    var incomparable =
      !!fromProvenance.hardware_fingerprint &&
      !!toProvenance.hardware_fingerprint &&
      fromProvenance.hardware_fingerprint !== toProvenance.hardware_fingerprint;
    var computeNumbers = !incomparable || options.forceIncomparable;

    var fromIndex = indexBenchmarks(from);
    var toIndex = indexBenchmarks(to);
    var ids = unionIds(fromIndex, toIndex);
    var results = [];
    var counts = {};

    ids.forEach(function (id) {
      var before = fromIndex[id];
      var after = toIndex[id];
      var entry = {
        id: id,
        name: (after || before).name,
        displayName: displayName((after || before).name),
        workload: (after || before).workload,
        variant: (after || before).variant,
        presence: { inFrom: !!before, inTo: !!after },
        metrics: [],
        classification: CLASS_INSUFFICIENT
      };
      if (!before || !after) {
        entry.classification = before ? CLASS_REMOVED : CLASS_NEW;
        var only = (after || before).samples || [];
        entry.metrics = metricsOf(only).map(function (metric) {
          var summary = summarize(sampleValues(only, metric));
          return {
            metric: metric,
            classification: entry.classification,
            fromMedian: summary.median,
            toMedian: summary.median,
            deltaPct: 0,
            deltaDefined: false,
            p: 0,
            tested: false,
            method: "",
            fromSamples: summary.n,
            toSamples: summary.n,
            fromSummary: summary,
            toSummary: summary
          };
        });
      } else if (!computeNumbers) {
        entry.classification = CLASS_INCOMPARABLE;
        entry.metrics = metricsOfBoth(before.samples, after.samples).map(function (metric) {
          var fromSummary = summarize(sampleValues(before.samples, metric));
          var toSummary = summarize(sampleValues(after.samples, metric));
          return {
            metric: metric,
            classification: CLASS_INCOMPARABLE,
            fromMedian: fromSummary.median,
            toMedian: toSummary.median,
            deltaPct: 0,
            deltaDefined: false,
            p: 0,
            tested: false,
            method: "",
            fromSamples: fromSummary.n,
            toSamples: toSummary.n,
            fromSummary: fromSummary,
            toSummary: toSummary
          };
        });
      } else {
        entry.metrics = metricsOfBoth(before.samples, after.samples).map(function (metric) {
          return evaluate(before.samples, after.samples, metric, options);
        });
        entry.classification = headline(entry.metrics);
      }
      counts[entry.classification] = (counts[entry.classification] || 0) + 1;
      results.push(entry);
    });

    return {
      from: from,
      to: to,
      incomparable: incomparable,
      forced: incomparable && options.forceIncomparable,
      options: options,
      results: results,
      geomeans: geomeansFor(results, computeNumbers),
      counts: counts
    };
  }

  function geomeansFor(results, computeNumbers) {
    var ratios = {};
    var set = {};
    results.forEach(function (result) {
      result.metrics.forEach(function (metric) {
        set[metric.metric] = true;
        if (!computeNumbers || !metric.deltaDefined || metric.fromMedian <= 0 || metric.toMedian <= 0) {
          return;
        }
        if (!ratios[metric.metric]) {
          ratios[metric.metric] = [];
        }
        ratios[metric.metric].push(metric.toMedian / metric.fromMedian);
      });
    });
    return orderedMetrics(set).map(function (metric) {
      var aggregate = geomean(ratios[metric] || []);
      return {
        metric: metric,
        ratio: aggregate.value,
        deltaPct: aggregate.count > 0 ? (aggregate.value - 1) * 100 : 0,
        count: aggregate.count,
        higherIsBetter: isHigherBetter(metric)
      };
    });
  }

  function metricResult(comparison, metric) {
    for (var index = 0; index < comparison.metrics.length; index++) {
      if (comparison.metrics[index].metric === metric) {
        return comparison.metrics[index];
      }
    }
    return null;
  }

  return {
    constants: {
      exactTestMaxSamples: EXACT_TEST_MAX_SAMPLES,
      minSamplesForSignificance: MIN_SAMPLES_FOR_SIGNIFICANCE,
      defaultAlpha: DEFAULT_ALPHA,
      defaultMinEffectPct: DEFAULT_MIN_EFFECT_PCT,
      defaultMinSamples: DEFAULT_MIN_SAMPLES
    },
    classes: {
      improved: CLASS_IMPROVED,
      regressed: CLASS_REGRESSED,
      unchanged: CLASS_UNCHANGED,
      insufficient: CLASS_INSUFFICIENT,
      new: CLASS_NEW,
      removed: CLASS_REMOVED,
      incomparable: CLASS_INCOMPARABLE
    },
    median: median,
    summarize: summarize,
    geomean: geomean,
    mannWhitneyU: mannWhitneyU,
    erfc: erfc,
    isHigherBetter: isHigherBetter,
    sampleValues: sampleValues,
    metricsOf: metricsOf,
    evaluate: evaluate,
    compareRuns: compareRuns,
    metricResult: metricResult,
    displayName: displayName
  };
});
